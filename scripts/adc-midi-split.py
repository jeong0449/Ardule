def extract_segment_messages(
    events: Sequence[AbsoluteEvent],
    start_tick: int,
    end_tick: int,
) -> List[Tuple[int, int, Message | MetaMessage]]:
    segment: List[Tuple[int, int, Message | MetaMessage]] = []
    time_sig, tempo = active_meta_before(events, start_tick)
    segment.append((0, -20, MetaMessage("time_signature", numerator=time_sig[0], denominator=time_sig[1], time=0)))
    segment.append((0, -19, MetaMessage("set_tempo", tempo=tempo, time=0)))

    for event in events:
        if event.tick < start_tick:
            continue
        if event.tick >= end_tick:
            break
        msg = event.message
        relative = event.tick - start_tick
        if isinstance(msg, Message) and getattr(msg, "channel", -1) == 9 and msg.type in {"note_on", "note_off"}:
            segment.append((relative, event.order, msg.copy(time=0)))
        elif isinstance(msg, MetaMessage) and msg.type in {"set_tempo", "time_signature"}:
            if relative == 0:
                continue
            segment.append((relative, event.order, msg.copy(time=0)))

    # Guarantee note-offs for any notes still active at the segment boundary.
    active: Dict[int, int] = {}
    for tick, _, msg in sorted(segment, key=lambda item: (item[0], item[1])):
        if not isinstance(msg, Message) or getattr(msg, "channel", -1) != 9:
            continue
        if msg.type == "note_on" and msg.velocity > 0:
            active[msg.note] = active.get(msg.note, 0) + 1
        elif msg.type == "note_off" or (msg.type == "note_on" and msg.velocity == 0):
            if active.get(msg.note, 0) > 0:
                active[msg.note] -= 1
    close_tick = max(0, end_tick - start_tick - 1)
    order = 10**9
    for note, count in sorted(active.items()):
        for _ in range(count):
            segment.append((close_tick, order, Message("note_off", channel=9, note=note, velocity=0, time=0)))
            order += 1

    return sorted(segment, key=lambda item: (item[0], item[1]))


def save_segment_midi(
    spec: PatternSpec,
    output_path: Path,
    mid: MidiFile,
    bars: Sequence[BarInfo],
    events: Sequence[AbsoluteEvent],
) -> None:
    start_tick = bars[spec.start_bar - 1].start_tick
    end_tick = bars[spec.end_bar - 1].end_tick
    messages = extract_segment_messages(events, start_tick, end_tick)

    out = MidiFile(type=0, ticks_per_beat=mid.ticks_per_beat)
    track = MidiTrack()
    out.tracks.append(track)

    last_tick = 0
    for absolute_tick, _, msg in messages:
        delta = absolute_tick - last_tick
        if delta < 0:
            fail(f"internal error while writing {spec.name}: negative delta time")
        last_tick = absolute_tick
        track.append(msg.copy(time=delta))
    segment_length = end_tick - start_tick
    track.append(MetaMessage("end_of_track", time=max(0, segment_length - last_tick)))
    out.save(output_path)



