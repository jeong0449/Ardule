def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog=SCRIPT_NAME,
        description=(
            "Split EXPORT=YES drum-pattern ranges from one original MIDI file "
            "or from all CSV-referenced MIDI files in a directory."
        ),
        epilog=(
            "File mode processes only matching CSV rows. Directory mode processes "
            "all EXPORT=YES CSV rows and requires every referenced MIDI file to be "
            "present. Default behavior writes one NAME.MID per selected row; use "
            "--dry-run to validate and preview without creating files."
        ),
    )
    parser.add_argument(
        "input",
        type=Path,
        help="Original MIDI file, or directory containing the original MIDI files",
    )
    parser.add_argument(
        "pattern_csv",
        type=Path,
        help="Reviewed ADC PatternLab CSV (a combined multi-file CSV is allowed)",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Output directory (default: <CSV directory>/split-midi)",
    )
    parser.add_argument(
        "--slot-maps",
        type=Path,
        default=None,
        help="Slot-map definition JSON (default: slot_map_definitions.json beside this script)",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Allow existing NAME.MID output files to be overwritten",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Validate inputs and print the split plan without writing files",
    )
    parser.add_argument("--version", action="version", version=VERSION_TEXT)
    return parser.parse_args(argv)


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)

    if not args.pattern_csv.is_file():
        fail(f"CSV file not found: {args.pattern_csv}")
    if not args.input.exists():
        fail(f"input path not found: {args.input}")
    if not (args.input.is_file() or args.input.is_dir()):
        fail(f"input must be a MIDI file or directory: {args.input}")

    slot_map_path = args.slot_maps or Path(__file__).with_name("slot_map_definitions.json")
    slot_maps = load_slot_maps(slot_map_path)
    specs = load_pattern_csv(args.pattern_csv)
    export_specs = [spec for spec in specs if spec.export]
    if not export_specs:
        fail("CSV has no EXPORT=YES rows")

    # Resolve source MIDI files.
    if args.input.is_file():
        if args.input.suffix.lower() not in {".mid", ".midi"}:
            fail(f"input file is not a MIDI file: {args.input}")
        wanted = args.input.name.casefold()
        selected_specs = [
            spec for spec in export_specs
            if Path(spec.file).name.casefold() == wanted
        ]
        if not selected_specs:
            fail(
                f"CSV has no EXPORT=YES rows for input MIDI {args.input.name!r}"
            )
        midi_jobs = [(args.input, selected_specs)]
        mode = "file"
    else:
        # Case-insensitive basename lookup; .mid and .midi are both accepted.
        available: Dict[str, Path] = {}
        duplicates: Dict[str, List[Path]] = {}
        for path in sorted(args.input.iterdir()):
            if not path.is_file() or path.suffix.lower() not in {".mid", ".midi"}:
                continue
            key = path.name.casefold()
            if key in available:
                duplicates.setdefault(key, [available[key]]).append(path)
            else:
                available[key] = path

        if duplicates:
            key, paths = next(iter(duplicates.items()))
            fail(
                "directory contains MIDI filenames that differ only by case: "
                + ", ".join(str(p.name) for p in paths)
            )

        specs_by_file: Dict[str, List[PatternSpec]] = {}
        original_names: Dict[str, str] = {}
        for spec in export_specs:
            key = Path(spec.file).name.casefold()
            specs_by_file.setdefault(key, []).append(spec)
            original_names.setdefault(key, Path(spec.file).name)

        missing = [
            original_names[key]
            for key in specs_by_file
            if key not in available
        ]
        if missing:
            preview = ", ".join(sorted(missing)[:12])
            extra = len(missing) - min(len(missing), 12)
            suffix = f" (+{extra} more)" if extra else ""
            fail(
                f"directory is missing {len(missing)} MIDI file(s) referenced by "
                f"EXPORT=YES CSV rows: {preview}{suffix}"
            )

        midi_jobs = [
            (available[key], specs_by_file[key])
            for key in sorted(specs_by_file, key=lambda k: original_names[k].casefold())
        ]
        mode = "directory"

    # Global output names must remain unique because all split files share one
    # output directory.
    seen_names: Dict[str, PatternSpec] = {}
    for _midi_path, job_specs in midi_jobs:
        for spec in job_specs:
            key = spec.name.casefold()
            if key in seen_names:
                first = seen_names[key]
                fail(
                    f"duplicate output NAME {spec.name!r} in CSV rows "
                    f"{first.row_number} and {spec.row_number}"
                )
            seen_names[key] = spec

    output_dir = args.output_dir or args.pattern_csv.parent / "split-midi"

    print(VERSION_TEXT)
    print(f"[OK] mode       : {mode}")
    print(f"[OK] input      : {args.input}")
    print(f"[OK] CSV        : {args.pattern_csv}")
    print(f"[OK] SLOT_MAPS  : {slot_map_path}")
    print(f"[OK] MIDI files : {len(midi_jobs)}")
    print(f"[OK] export rows: {sum(len(job_specs) for _, job_specs in midi_jobs)}")
    print(f"[PLAN] split MIDI -> {output_dir}")

    prepared = []
    for midi_path, job_specs in midi_jobs:
        try:
            mid = MidiFile(str(midi_path))
        except Exception as exc:
            fail(f"cannot read MIDI {midi_path}: {exc}")
        if mid.type not in (0, 1):
            fail(f"{midi_path.name}: only SMF Type 0 or 1 is supported, got Type {mid.type}")

        events = merged_absolute_events(mid)
        total_tick = max((event.tick for event in events), default=0)
        bars = build_bar_map(
            mid.ticks_per_beat,
            collect_time_signatures(events),
            total_tick,
        )
        selected = validate_specs(job_specs, midi_path, slot_maps, bars, events)
        prepared.append((midi_path, mid, bars, events, selected))

        print(
            f"       {midi_path.name}: {len(selected)} pattern(s) "
            f"· Type {mid.type} · TPQ {mid.ticks_per_beat} · {len(bars)} bars"
        )
        for spec in selected:
            print(f"         {spec.name}.MID <- bars {spec.start_bar}-{spec.end_bar}")

    if args.dry_run:
        print("[DRY RUN] Validation completed; no files were written.")
        return 0

    output_dir.mkdir(parents=True, exist_ok=True)
    conflicts = [
        output_dir / f"{spec.name}.MID"
        for _, _, _, _, selected in prepared
        for spec in selected
        if (output_dir / f"{spec.name}.MID").exists()
    ]
    if conflicts and not args.overwrite:
        fail(
            f"split MIDI output already exists: {conflicts[0]} "
            f"(use --overwrite)"
        )

    split_count = 0
    for midi_path, mid, bars, events, selected in prepared:
        for spec in selected:
            output_path = output_dir / f"{spec.name}.MID"
            save_segment_midi(spec, output_path, mid, bars, events)
            split_count += 1
            print(
                f"[SPLIT] {output_path.name} <- "
                f"{midi_path.name} bars {spec.start_bar}-{spec.end_bar}"
            )

    print(f"[DONE] split MIDI: {split_count}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
