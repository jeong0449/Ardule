def merged_absolute_events(mid: MidiFile) -> List[AbsoluteEvent]:
    merged = mido.merge_tracks(mid.tracks) if mid.type == 1 else mid.tracks[0]
    events: List[AbsoluteEvent] = []
    tick = 0
    for order, msg in enumerate(merged):
        tick += msg.time
        events.append(AbsoluteEvent(tick, order, msg.copy(time=0)))
    return events


def collect_time_signatures(events: Sequence[AbsoluteEvent]) -> List[Tuple[int, int, int]]:
    values: Dict[int, Tuple[int, int]] = {0: (4, 4)}
    for event in events:
        msg = event.message
        if isinstance(msg, MetaMessage) and msg.type == "time_signature":
            values[event.tick] = (int(msg.numerator), int(msg.denominator))
    return [(tick, num, den) for tick, (num, den) in sorted(values.items())]


def build_bar_map(tpq: int, time_signatures: Sequence[Tuple[int, int, int]], total_tick: int) -> List[BarInfo]:
    if tpq <= 0:
        fail(f"invalid ticks_per_beat: {tpq}")
    if total_tick <= 0:
        fail("MIDI contains no timed content")

    bars: List[BarInfo] = []
    ts_index = 0
    tick = 0
    number = 1
    while tick < total_tick:
        while ts_index + 1 < len(time_signatures) and time_signatures[ts_index + 1][0] <= tick:
            ts_index += 1
        _, num, den = time_signatures[ts_index]
        nominal_end = tick + max(1, round(tpq * num * 4 / den))
        if ts_index + 1 < len(time_signatures):
            next_change = time_signatures[ts_index + 1][0]
            if tick < next_change < nominal_end:
                nominal_end = next_change
        bars.append(BarInfo(number, tick, nominal_end, num, den))
        tick = nominal_end
        number += 1
    return bars


def active_meta_before(events: Sequence[AbsoluteEvent], start_tick: int) -> Tuple[Tuple[int, int], int]:
    time_sig = (4, 4)
    tempo = 500000
    for event in events:
        if event.tick > start_tick:
            break
        msg = event.message
        if isinstance(msg, MetaMessage):
            if msg.type == "time_signature":
                time_sig = (int(msg.numerator), int(msg.denominator))
            elif msg.type == "set_tempo":
                tempo = int(msg.tempo)
    return time_sig, tempo


def drum_note_ons(events: Sequence[AbsoluteEvent], start_tick: int, end_tick: int) -> List[AbsoluteEvent]:
    return [
        event
        for event in events
        if start_tick <= event.tick < end_tick
        and isinstance(event.message, Message)
        and getattr(event.message, "channel", -1) == 9
        and event.message.type == "note_on"
        and event.message.velocity > 0
    ]


