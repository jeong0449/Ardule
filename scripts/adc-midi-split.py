#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""adc-midi-split.py 260818b

Split selected drum-pattern ranges from original MIDI files according to an
ADC PatternLab CSV.

Inputs
------
1. One original MIDI file, or a directory containing original MIDI files
2. Reviewed PatternLab CSV generated by adc-patternlab.py
3. slot_map_definitions.json (default: beside this script)

Behavior:
    - File input: process only CSV rows whose FILE matches that MIDI filename.
    - Directory input: process all EXPORT=YES CSV rows and locate each source
      MIDI by filename in that directory.
    - By default, save one CH10 MIDI file per EXPORT=YES row.
    - Use --dry-run to validate inputs and print the split plan without writing
      any files.

The script performs no genre, subdivision, name, duplicate, or slot-map
inference. Those decisions are taken directly from the reviewed CSV.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Set, Tuple

import mido
from mido import Message, MetaMessage, MidiFile, MidiTrack


SCRIPT_NAME = "adc-midi-split.py"
VERSION = "260818b"
VERSION_TEXT = f"{SCRIPT_NAME} {VERSION}"

REQUIRED_COLUMNS = {
    "FILE",
    "START_BAR",
    "END_BAR",
    "NAME",
    "TIME_SIG",
    "SLOT_MAP",
    "EXPORT",
    "SUBDIV",
    "SOURCE",
}
VALID_SUBDIV = {"16", "32", "8T", "16T"}
NAME_RE = re.compile(r"^[A-Z0-9]{3}_[0-9]{4}$")




@dataclass(frozen=True)
class SlotDefinition:
    index: int
    abbrev: str
    extended: str
    representative_midi: int
    allowed_notes: Tuple[int, ...]


@dataclass(frozen=True)
class SlotMapDefinition:
    map_id: int
    name: str
    slots: Tuple[SlotDefinition, ...]

    @property
    def accepted_notes(self) -> Set[int]:
        out: Set[int] = set()
        for slot in self.slots:
            out.update(slot.allowed_notes)
        return out

    def slot_for_note(self, note: int) -> Optional[int]:
        for slot in self.slots:
            if note in slot.allowed_notes:
                return slot.index
        return None


@dataclass(frozen=True)
class PatternSpec:
    row_number: int
    file: str
    start_bar: int
    end_bar: int
    name: str
    time_sig: str
    slot_map: str
    export: bool
    genre: str
    subdiv: str
    orn: bool
    duplicate_of: str
    source: str


@dataclass(frozen=True)
class BarInfo:
    number: int
    start_tick: int
    end_tick: int
    numerator: int
    denominator: int


@dataclass(frozen=True)
class AbsoluteEvent:
    tick: int
    order: int
    message: Message | MetaMessage


# ---------------------------------------------------------------------------
# Generic helpers
# ---------------------------------------------------------------------------


def fail(message: str) -> "NoReturn":
    raise SystemExit(f"[ERROR] {message}")


def parse_yes_no(value: str, *, field: str, row_number: int) -> bool:
    normalized = value.strip().upper()
    if normalized == "YES":
        return True
    if normalized == "NO":
        return False
    fail(f"CSV row {row_number}: {field} must be YES or NO, got {value!r}")


def parse_time_signature(value: str, *, row_number: int) -> Tuple[int, int]:
    m = re.fullmatch(r"([1-9][0-9]*)/([1-9][0-9]*)", value.strip())
    if not m:
        fail(f"CSV row {row_number}: invalid TIME_SIG {value!r}")
    num, den = int(m.group(1)), int(m.group(2))
    if den & (den - 1):
        fail(f"CSV row {row_number}: TIME_SIG denominator must be a power of two: {value!r}")
    return num, den


def safe_output_stem(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", name).strip("._") or "patterns"




